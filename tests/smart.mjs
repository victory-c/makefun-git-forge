import assert from 'node:assert/strict';
import { createRepo, commitFiles, setRef, updateRepo } from '../forge.ts';
import { infoRefs, uploadPack } from '../smart.ts';
import { pkt, DELIM, FLUSH } from '../git.ts';
const repo=createRepo({name:'git-cache'});
const owner=repo.owner;
const first=commitFiles(repo,'main',new Map([['file.txt',Buffer.from('first\n')]]),'first');
const advert=()=>infoRefs(owner,repo.name,'git-upload-pack','version=2');
assert.equal(advert(),advert());
const request=Buffer.concat([pkt('command=ls-refs\n'),DELIM,pkt('symrefs\n'),pkt('peel\n'),FLUSH]);
const refs=()=>uploadPack(owner,repo.name,request,'version=2');
const old=refs();assert.equal(old,refs());assert.match(old.body.toString(),new RegExp(first+' HEAD'));
const second=commitFiles(repo,'main',new Map([['file.txt',Buffer.from('second\n')]]),'second');
assert.notEqual(refs(),old);assert.match(refs().body.toString(),new RegExp(second+' HEAD'));
setRef(repo,'refs/heads/other',first);
updateRepo(repo,{default_branch:'other'});
assert.match(refs().body.toString(),new RegExp(first+' HEAD symref-target:refs/heads/other'));
setRef(repo,'refs/heads/other',null);
assert.doesNotMatch(refs().body.toString(),/refs\/heads\/other\n/);
assert.equal(infoRefs('stranger',repo.name,'git-upload-pack','version=2').status,404);
console.log('git response caches: identity reuse, ref mutations, default-branch change, deletion and owner isolation passed');
